/** Типы данных, которые можно использовать в столбцах таблицы. */
public enum DataType {
    INT,      // целое число, в Java хранится как Long
    DOUBLE,   // дробное число, в Java хранится как Double
    STRING,   // строка, в Java хранится как String
    DATE,     // дата вида 2024-12-31, в Java хранится как LocalDate
    BOOLEAN   // TRUE или FALSE, в Java хранится как Boolean
}
